def parse_allow_paths_from_ctx(raw: str) -> list[str]:
    """Parse StepContext.allow_paths (`- path` lines or comma-separated)."""
    if not raw or raw.strip() in {"", _LT_95}:
        return []
    paths: list[str] = []
    for line in raw.replace(",", "\n").splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("- "):
            s = s[2:].strip()
        s = s.strip('"').strip("'")
        if s:
            paths.append(s)
    return paths


